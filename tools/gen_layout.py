"""Regenerates src/layout_x86.inc (struct offsets for the x86 assembly) and
src/layout_check.h (static checks that keep them in step with the C structs).

  python tools/gen_layout.py      # needs the x86 MSVC tools (vcvars32 via vswhere)

Run it after changing a struct the assembly uses: the C build fails until then."""
import subprocess, tempfile
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
VS = Path(r'C:\Program Files (x86)\Microsoft Visual Studio')

def vcvars():
    found = subprocess.run([str(VS / 'Installer/vswhere.exe'), '-latest', '-products', '*', '-property', 'installationPath'],
                           capture_output=True, text=True, check=True).stdout.strip()
    return Path(found) / 'VC/Auxiliary/Build/vcvars32.bat'

def offsets(full):
    with tempfile.TemporaryDirectory() as work:
        exe = Path(work) / 'layout.exe'
        bat = Path(work) / 'build.bat'
        bat.write_text(f'@call "{vcvars()}" >nul\n@cl /nologo /DJBV_PROFILE_FULL={int(full)} /I"{ROOT / "src"}" /I"{ROOT / "include"}" '
                       f'"{ROOT / "tools/layout.c"}" /Fo"{work}\\\\" /Fe"{exe}" >nul\n@"{exe}"\n')
        out = subprocess.run(['cmd', '/c', str(bat)], capture_output=True, text=True, check=True).stdout
    return [line.split() for line in out.splitlines() if line.strip()]

def generate():
    full, core = offsets(True), offsets(False)
    inc = ['; Generated by tools/gen_layout.py from the C structs; checked by src/layout_check.h.', 'IF JBV_PROFILE_FULL']
    inc += [f'{name} EQU {value}' for name, value, _, _ in full] + ['ELSE'] + [f'{name} EQU {value}' for name, value, _, _ in core] + ['ENDIF', '']
    chk = ['/* Generated by tools/gen_layout.py: src/layout_x86.inc matches these structs. */',
           '#define JBV_GEN_LAYOUT(name, ok) typedef char jbv_gen_layout_##name[(ok) ? 1 : -1]']
    def checks(rows):
        return [f'JBV_GEN_LAYOUT({name}, {"sizeof(" + t + ")" if f == "sizeof" else "offsetof(" + t + ", " + f + ")"} == {value});' for name, value, t, f in rows]
    chk += ['#if JBV_PROFILE_FULL'] + checks(full) + ['#else'] + checks(core) + ['#endif', '']
    (ROOT / 'src/layout_x86.inc').write_text('\n'.join(inc), newline='\n')
    (ROOT / 'src/layout_check.h').write_text('\n'.join(chk), newline='\n')

if __name__ == '__main__':
    generate()
